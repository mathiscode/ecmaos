// Writes the C side of the GL command stream (see core/kernel/src/tree/lib/gl-commands.ts): one GLES2 function per
// command that packs its arguments into the stream, and a table of them for eglGetProcAddress. The commands are those
// of gl-commands.json, the file the kernel's decoder reads. Usage: node gen-cmds.mjs gl-commands.json > ecmaos_gl_cmds.inc
import { readFileSync } from 'node:fs'

const { commands } = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const upper = name => name[0].toUpperCase() + name.slice(1)
const out = ['/* generated by gen-cmds.mjs from gl-commands.json; do not edit */', '']

for (const { op, name, args, sig } of commands) {
  if (sig.length !== args.length) throw new Error(`${name}: ${args.length} arguments, ${sig.length} letters`)
  const names = args.map(arg => arg.trim().split(/[\s*]+/).at(-1))
  const body = args.length ? [`  uint32_t w[${args.length}];`, ...names.map((n, i) => `  w[${i}] = ${sig[i] === 'f' ? `ecmaos_f2u(${n})` : `(uint32_t)${n}`};`), `  ecmaos_emit(${op}, ${args.length}, w);`] : [`  ecmaos_emit(${op}, 0, NULL);`]
  out.push(`GL_APICALL void GL_APIENTRY gl${upper(name)}(${args.join(', ') || 'void'})`, '{', ...body, '}', '')
}
out.push('static const struct { const char *name; void *function; } ecmaos_gl_commands[] = {')
for (const { name } of commands) out.push(`  { "gl${upper(name)}", (void *)gl${upper(name)} },`)
out.push('  { NULL, NULL }', '};', '')
process.stdout.write(out.join('\n'))
