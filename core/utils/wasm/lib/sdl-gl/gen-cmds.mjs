// Writes the C side of the GL command stream (see core/kernel/src/tree/lib/gl-commands.ts): an ECMAOS_OP_ constant for
// each command, one GLES2 function per command that packs its arguments into the stream (the commands marked `manual`
// are written by hand in ecmaos_gl.c, which has to handle client memory), and a table of the functions for
// eglGetProcAddress. The commands are those of gl-commands.json, the file the kernel's decoder reads.
// Usage: node gen-cmds.mjs gl-commands.json > ecmaos_gl_cmds.inc
import { readFileSync } from 'node:fs'

const { commands } = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const upper = name => name[0].toUpperCase() + name.slice(1)
const out = ['/* generated by gen-cmds.mjs from gl-commands.json; do not edit */', '']
const functionOf = command => command.fn ?? `gl${upper(command.name)}`

for (const command of commands) out.push(`#define ECMAOS_OP_${command.key ?? command.name} ${command.op}`)
out.push('')

for (const command of commands) {
  const { op, args, sig, manual } = command
  if (manual || functionOf(command) === '') continue
  if (sig.length !== args.length) throw new Error(`${command.name}: ${args.length} arguments, ${sig.length} letters`)
  if (/[bFIS]/.test(sig)) throw new Error(`${command.name}: a command with a blob is written by hand`)
  const names = args.map(arg => arg.trim().split(/[\s*]+/).at(-1))
  const body = args.length ? [`  uint32_t words_[${args.length}];`, ...names.map((n, i) => `  words_[${i}] = ${sig[i] === 'f' ? `ecmaos_f2u(${n})` : `(uint32_t)${n}`};`), `  ecmaos_emit(${op}, ${args.length}, words_);`] : [`  ecmaos_emit(${op}, 0, NULL);`]
  out.push(`GL_APICALL void GL_APIENTRY ${functionOf(command)}(${args.join(', ') || 'void'})`, '{', ...body, '}', '')
}
out.push('static const struct { const char *name; void *function; } ecmaos_gl_commands[] = {')
const listed = new Set()
for (const command of commands) {
  const fn = functionOf(command)
  if (fn === '' || listed.has(fn)) continue
  listed.add(fn)
  out.push(`  { "${fn}", (void *)${fn} },`)
}
out.push('  { NULL, NULL }', '};', '')
process.stdout.write(out.join('\n'))
